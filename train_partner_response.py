def atomic_save(payload,path):
    temp=path.with_suffix('.tmp');torch.save(payload,temp);temp.replace(path)


def actor_states(agents):return {r:copy.deepcopy(a.state_dict()) for r,a in agents.items()}


def set_actors(agents,states):
    for r,a in agents.items():a.load_state_dict(states[r])


def selection_score(metrics):
    positive=metrics['correct']['nll'];negative=metrics['shuffled']['nll']
    return positive+.05*max(0,positive-negative+.03)


def mean_reward(ep):
    return float(np.mean([s['reward'] for s in ep['steps'] if s['components']]))


def make_anchor(cache,update):
    batches={}
    for role,pairs in cache.items():
        chosen=[pairs[(update*8+i)%len(pairs)] for i in range(min(8,len(pairs)))]
        batches[role]=(pr.concatenate([x['correct'] for x in chosen]),pr.concatenate([x['shuffled'] for x in chosen]))
    def anchor(role,actor):
        positive,negative=batches[role]
        pos=pr.policy_nll(actor,positive).mean();neg=pr.policy_nll(actor,negative).mean()
        return .05*pos+.005*torch.nn.functional.softplus((pos-neg+.03)/.1)*.1
    return anchor


