        '', 'Cautions: most source examples are pairs; full-trio supervised validation is unavailable. Cello composition diversity remains limited. Source voices were pruned to role limits; no target pitches or onsets were invented. Near-duplicate compositions and overlap with backbone pretraining have not been fully audited. This small curriculum does not establish long-form cinematic composition or originality.',
